"""Utility helpers for serialising custom realtime‑collab objects.

The core protocol messages are Pydantic models defined in ``model.py``; they already
support ``.dict()`` and ``json()``.  However, higher‑level objects such as the in‑
memory ``Room`` store a CRDT document instance that is not JSON‑serialisable out of
the box.  The helpers below provide a small, test‑covered API to convert those
objects to plain ``dict`` structures that can be returned from FastAPI routes or
sent over a WebSocket.
"""

from __future__ import annotations

from typing import Any, Dict

from .store import Room

def room_to_dict(room: Room) -> Dict[str, Any]:
    """Serialise a :class:`Room` instance to a plain dictionary.

    The function extracts the public attributes required by the UI:

    * ``doc_id`` – identifier of the collaboration document.
    * ``users`` – list of currently connected usernames.
    * ``version`` – current document version.
    * ``content`` – the underlying CRDT document content as a string if it
      implements a ``to_text()`` method; otherwise the raw ``doc`` is returned.
    """
    content = getattr(room.doc, "to_text", None)
    if callable(content):
        content = content()
    else:
        content = getattr(room.doc, "content", None)

    return {
        "doc_id": room.doc_id,
        "users": list(room.users),
        "version": getattr(room.doc, "version", None),
        "content": content,
    }

def dict_to_room(data: Dict[str, Any]) -> Room:
    """Re‑create a :class:`Room` from a dictionary generated by ``room_to_dict``.

    This is primarily used in unit tests to verify round‑trip serialisation.  It
    assumes the ``Room`` constructor can accept ``doc_id`` and an optional
    ``initial_doc``.  The ``users`` list is re‑attached after construction.
    """
    from .store import Room as RoomClass

    room = RoomClass(doc_id=data["doc_id"], initial_doc=data.get("content"))
    # Populate the user set – ``Room`` expects a ``set``.
    room.users = set(data.get("users", []))
    return room
